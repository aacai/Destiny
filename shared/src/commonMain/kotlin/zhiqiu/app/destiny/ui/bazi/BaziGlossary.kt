/** 缩写十神 → 全称（如 比→比肩） */
fun tenGodFull(name: String): String = when (name) {
    "比" -> "比肩"
    "劫" -> "劫财"
    "食" -> "食神"
    "伤" -> "伤官"
    "才" -> "偏财"
    "财" -> "正财"
    "杀" -> "七杀"
    "官" -> "正官"
    "枭" -> "偏印"
    "印" -> "正印"
    else -> name
}

/** 八字术语资料弹窗：标题 + 标签 + 逐条「条目 → 说明」 */
@Composable
fun BaziInfoDialog(item: GlossaryItem, onDismiss: () -> Unit) {
    Dialog(onDismissRequest = onDismiss) {
        Column(
            modifier = Modifier
                .background(Panel, RoundedCornerShape(10.dp))
                .padding(20.dp),
        ) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Text(item.title, fontSize = 18.sp, color = Ink, fontWeight = FontWeight.Bold)
                Spacer(modifier = Modifier.width(8.dp))
                Text(item.tag, fontSize = 12.sp, color = Accent, fontWeight = FontWeight.SemiBold)
            }
            Spacer(modifier = Modifier.height(12.dp))
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .height(360.dp)
                    .verticalScroll(rememberScrollState()),
                verticalArrangement = Arrangement.spacedBy(10.dp),
            ) {
                item.rows.forEach { (label, text) ->
                    Row {
                        Text(
                            label,
                            fontSize = 13.sp,
                            color = Accent,
                            fontWeight = FontWeight.SemiBold,
                            modifier = Modifier.width(60.dp),
                        )
                        Text(text, fontSize = 14.sp, color = Ink, lineHeight = 21.sp, modifier = Modifier.weight(1f))
                    }
                }
            }
            Spacer(modifier = Modifier.height(14.dp))
            Text(
                "知道了",
                color = Accent,
                fontSize = 14.sp,
                fontWeight = FontWeight.SemiBold,
                modifier = Modifier
                    .align(Alignment.End)
                    .clickable(onClick = onDismiss),
            )
        }
    }
}
