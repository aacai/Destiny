            "本盘命中政余喜格「$name」。主吉庆、得地、助贵之类，宜参看同宫星曜与大限再断。"
        } else {
            "本盘命中政余忌格「$name」。主耗泄、受克、失垣之类，宜参看解救星与大限再断。"
        }

