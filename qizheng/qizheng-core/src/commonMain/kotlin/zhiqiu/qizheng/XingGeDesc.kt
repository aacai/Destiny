            val t = name.removePrefix("日月夹")
            "日月一左一右夹辅「$t」。夹吉宫主得助，夹凶宫主牵绊，宜合看宫主庙旺。"
        }
        name.startsWith("命临") -> {
            val t = name.removePrefix("命临")
            "命宫临「$t」。神煞入命，吉则一生得力，凶则性情运途多扰，当以喜忌神煞分辨。"
